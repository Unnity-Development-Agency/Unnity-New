const {chromium,expect}=require('@playwright/test');
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 const errors=[];page.on('pageerror',e=>errors.push(e.message));page.on('console',m=>{if(m.type()==='error')errors.push(m.text())});
 await page.clock.install({time:new Date('2026-01-01T00:00:00Z')});
 await page.clock.pauseAt(new Date('2026-01-01T00:01:00Z'));
 await page.goto('http://localhost:3000',{waitUntil:'networkidle'});
 await page.waitForSelector('[data-ready="true"]');
 const base=await page.locator('[data-ribbon-edge]').getAttribute('d');
 const crop={x:135,y:125,width:265,height:165};
 await page.clock.runFor(100);
 const jellyA=await page.screenshot({clip:crop});
 await page.clock.runFor(400);
 expect(jellyA.equals(await page.screenshot({clip:crop}))).toBe(false);
 await page.clock.runFor(1680);
 expect(await page.locator('[data-ribbon-edge]').getAttribute('d')).toBe(base);
 await page.clock.runFor(60);
 const impact=await page.locator('[data-ribbon-edge]').getAttribute('d');
 expect(impact).not.toBe(base);
 await page.screenshot({path:'node_modules/.cache/hero-qa/impact-new.png'});
 await page.clock.runFor(6560);
 expect(await page.locator('[data-ribbon-edge]').getAttribute('d')).toBe(base);
 const visibleEmitter=await page.screenshot({clip:crop});
 await page.clock.runFor(5000);
 expect(visibleEmitter.equals(await page.screenshot({clip:crop}))).toBe(false);
 await page.screenshot({path:'node_modules/.cache/hero-qa/emitter-permanent.png'});
 await page.clock.runFor(2600);
 await page.emulateMedia({reducedMotion:'reduce'});
 await page.screenshot({path:'node_modules/.cache/hero-qa/brands-new.png'});
 expect(errors).toEqual([]);
 console.log('PASS: jelly continuously moves, ribbon reacts within 40ms of rim contact, settles exactly, permanent emitter remains animated, no console errors.');
 await browser.close();
})().catch(e=>{console.error(e);process.exit(1)});
