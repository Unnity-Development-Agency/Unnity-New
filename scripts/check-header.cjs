const { chromium, expect } = require('@playwright/test');
const fs = require('fs');
const baseUrl=process.env.HEADER_TEST_URL || 'http://localhost:3000';
(async()=>{
 const browser=await chromium.launch({channel:'chrome',headless:true});
 try {
 const page=await browser.newPage({viewport:{width:1440,height:900}});
 page.setDefaultTimeout(15000);
 const errors=[];
 page.on('pageerror',error=>errors.push(error.message));
 page.on('console',message=>{if(message.type()==='error')errors.push(message.text())});
 const dir='node_modules/.cache/header-qa';fs.mkdirSync(dir,{recursive:true});
 await page.goto(baseUrl,{waitUntil:'networkidle'});
 await page.waitForSelector('[data-ready="true"]');
 const header=page.locator('header');
 await expect(header).toHaveAttribute('data-hidden','false');
 await page.screenshot({path:dir+'/desktop.png'});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await page.evaluate(()=>scrollTo(0,80));await page.waitForTimeout(120);
 await expect(header).toHaveAttribute('data-hidden','true');
 await page.waitForTimeout(600);
 expect(await header.evaluate(el=>el.inert)).toBe(true);
 await page.screenshot({path:dir+'/hidden.png'});
 await page.evaluate(()=>scrollTo(0,77));
 await expect(header).toHaveAttribute('data-hidden','false');
 await page.waitForTimeout(650);
 await expect(page.getByRole('link',{name:'Contact us'})).toBeVisible();
 await page.getByRole('button',{name:'See our work'}).click();
 await expect(page.locator('#work-navigation a')).toHaveCount(3);
 await page.screenshot({path:dir+'/dropdown.png'});
 await page.keyboard.press('Escape');
 await expect(page.getByRole('button',{name:'See our work'})).toBeFocused();
 await expect(page.getByRole('button',{name:'See our work'})).toHaveAttribute('aria-expanded','false');
 await page.getByRole('link',{name:'Contact us'}).click();
 console.log('Checking contact navigation');
 await expect(page).toHaveURL(/\/contact$/, {timeout:30000});
 await expect(page.getByRole('heading',{level:1,name:'Contact us'})).toBeVisible();
 expect(await page.locator('head meta[name="robots"]').last().getAttribute('content')).toContain('noindex');
 await page.getByRole('link',{name:'Unnity Media home'}).click();
 await expect(page).toHaveURL(baseUrl+'/', {timeout:30000});
 console.log('Checking mobile menu');
 await page.setViewportSize({width:390,height:844});
 await page.evaluate(()=>scrollTo(0,0));
 await expect(page.getByRole('button',{name:'Open navigation'})).toBeVisible();
 await page.getByRole('button',{name:'Open navigation'}).click();
 await expect(page.getByRole('button',{name:'Close navigation'})).toBeVisible();
 await page.getByRole('button',{name:'See our work'}).click();
 await page.screenshot({path:dir+'/mobile-menu.png',fullPage:true});
 await page.locator('#work-navigation').getByRole('link',{name:/Paid media/}).click();
 await expect(page).toHaveURL(/\/work\/paid-media$/, {timeout:30000});
 await expect(page.getByRole('button',{name:'Open navigation'})).toHaveAttribute('aria-expanded','false');
 await page.getByRole('link',{name:'Unnity Media home'}).click();
 await page.setViewportSize({width:320,height:740});
 expect(await page.evaluate(()=>document.documentElement.scrollWidth>innerWidth)).toBe(false);
 await page.screenshot({path:dir+'/small-mobile.png',fullPage:true});
 await page.emulateMedia({reducedMotion:'reduce'});
 expect(await page.locator('.wind-surface').evaluate(el=>getComputedStyle(el).transitionDuration)).toBe('0s');
 expect(errors).toEqual([]);
 console.log('PASS: scroll-down hides, 3px up reveals, hidden header inert, dropdown/Escape, real routes, mobile navigation, 320px overflow, reduced motion, no browser errors.');
 } finally {await browser.close()}
})().catch(e=>{console.error(e);process.exit(1)});

