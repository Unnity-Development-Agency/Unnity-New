const assert = require('node:assert/strict');
const fs = require('node:fs');
const cp = require('node:child_process');
(async () => {
 const response = await fetch('http://localhost:3000');
 assert.equal(response.status, 200);
 const html = await response.text();
 assert.match(html, /Unnity Media \| Digital Marketing/);
 assert.match(html, /name="description"/);
 assert.match(html, /property="og:title"/);
 assert.match(html, /name="twitter:card" content="summary_large_image"/);
 assert.equal((html.match(/<h1\b/g)||[]).length, 1);
 const schema = html.match(/<script type="application\/ld\+json">([\s\S]*?)<\/script>/);
 assert(schema);
 assert.equal(JSON.parse(schema[1])['@type'], 'Organization');
 const robots = await fetch('http://localhost:3000/robots.txt');
 assert.equal(robots.status,200);
 assert.match(await robots.text(), /Allow: \//);
 const sitemap = await fetch('http://localhost:3000/sitemap.xml');
 assert.equal(sitemap.status,200);
 assert.match(await sitemap.text(), /<urlset/);
 const image = await fetch('http://localhost:3000/opengraph-image');
 assert.equal(image.status,200);
 const png = Buffer.from(await image.arrayBuffer());
 assert.equal(png.readUInt32BE(16),1200);
 assert.equal(png.readUInt32BE(20),630);
 const source = fs.readFileSync('src/app/site.js','utf8');
 const moduleUrl = 'data:text/javascript;base64,'+Buffer.from(source).toString('base64');
 const probe = 'const {site}=await import('+JSON.stringify(moduleUrl)+'); process.stdout.write(JSON.stringify(site));';
 const site = JSON.parse(cp.execFileSync(process.execPath,['--input-type=module','-e',probe],{env:{...process.env,NEXT_PUBLIC_SITE_URL:'https://seo-test.example',SITE_NOINDEX:'false'},encoding:'utf8'}));
 assert.equal(site.url,'https://seo-test.example');
 assert.equal(site.noindex,false);
 console.log('PASS: server-rendered SEO metadata, one H1, JSON-LD, robots, sitemap, 1200x630 social image, configurable public domain.');
})().catch(e=>{console.error(e);process.exit(1)});
